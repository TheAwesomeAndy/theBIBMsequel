#!/usr/bin/env python3
"""Print Phase 1 results as Markdown tables and write docs/PHASE1_RESULTS_TABLES.md.

Reads outputs/aggregate/p1a_window_study.json, p1b_reservoir_dynamics.json and
p1c_permutation.json (whichever exist). Numbers only; interpretation goes in the report.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AGG = ROOT / "outputs" / "aggregate"


def ci(d):
    return f"{d['BA']:.3f} [{d['ci95'][0]:.3f}, {d['ci95'][1]:.3f}]"


def diff(d):
    return f"{d['mean_diff']:+.3f} [{d['ci95'][0]:+.3f}, {d['ci95'][1]:+.3f}]"


def p1a(lines):
    f = AGG / "p1a_window_study.json"
    if not f.exists():
        return
    r = json.loads(f.read_text())
    encs = ["BSC6", "BSC1", "Amp6", "ERP-window", "Band-power"]
    lines += ["## P1a. Clean BA by preprocessing and reservoir window", "",
              "| decimation, norm, window | " + " | ".join(encs) + " | rate |",
              "|---|" + "---|" * (len(encs) + 1)]
    for key, c in r["cells"].items():
        e = c["encoders"]
        lines.append(f"| {key.replace('|', ', ')} | " + " | ".join(ci(e[n]["BA"]["clean"]) for n in encs)
                     + f" | {c['firing_rate']:.3f} |")
    lines += ["", "## P1a. BSC6 minus other encoders (clean, paired)", "",
              "| cell | " + " | ".join(encs[1:]) + " |", "|---|" + "---|" * (len(encs) - 1)]
    for key, c in r["cells"].items():
        lines.append(f"| {key.replace('|', ', ')} | " + " | ".join(
            diff(c["BSC6_minus"][n]["clean"]) for n in encs[1:]) + " |")
    lines += ["", "## P1a. 30% dropout: BA by condition", ""]
    conds = ["clean", "fc30_zero", "fc30_mean", "fc30_knn", "fc30_spatial", "sig30", "refit30"]
    for key, c in r["cells"].items():
        lines += [f"**{key.replace('|', ', ')}**", "", "| encoder | " + " | ".join(conds) + " |",
                  "|---|" + "---|" * len(conds)]
        for n in encs:
            b = c["encoders"][n]["BA"]
            lines.append(f"| {n} | " + " | ".join(f"{b[k]['BA']:.3f}" for k in conds) + " |")
        lines += ["", "| encoder | mean-zero | refit-zero | non-centeredness | fill-bias index |",
                  "|---|---|---|---|---|"]
        for n in encs:
            e = c["encoders"][n]
            th = e["theory"].get("fc30_zero", {})
            lines.append(f"| {n} | {diff(e['fill_contrasts']['fc30_mean_minus_fc30_zero'])} | "
                         f"{diff(e['fill_contrasts']['refit30_minus_fc30_zero'])} | "
                         f"{th.get('non_centeredness', float('nan')):.3f} | "
                         f"{th.get('fill_bias_index', float('nan')):.3f} |")
        lines.append("")


def p1b(lines):
    f = AGG / "p1b_reservoir_dynamics.json"
    if not f.exists():
        return
    r = json.loads(f.read_text())
    seeds = list(r["seeds"])
    rhos = list(r["seeds"][seeds[0]]["BA"])
    lines += ["## P1b. Reservoir over weight draws", "",
              "| rho | BA mean | BA sd | min | max |", "|---|---|---|---|---|"]
    for rho in rhos:
        v = [r["seeds"][s]["BA"][rho]["BA"] for s in seeds]
        lines.append(f"| {rho} | {sum(v)/len(v):.3f} | {r['across_seeds'][rho]['BA_sd']:.3f} | "
                     f"{min(v):.3f} | {max(v):.3f} |")
    lines += ["", "| seed | rho* (half-max damage) | rho_c (m = 1) | p_theta at 0.9 | "
              "rho0 - rho0.9 |", "|---|---|---|---|---|"]
    for s in seeds:
        x = r["seeds"][s]
        pt = x["dynamics"].get("0.9", {}).get("p_theta", float("nan"))
        d = diff(x["rho0_minus_rho0.9"]) if "rho0_minus_rho0.9" in x else "n/a"
        fmt = lambda v: "none" if v is None else f"{v:.2f}"  # noqa: E731
        lines.append(f"| {s} | {fmt(x['rho_star_half_max_damage'])} | "
                     f"{fmt(x['rho_c_branching_m_eq_1'])} | {pt:.3f} | {d} |")
    lines.append("")


def p1c(lines):
    f = AGG / "p1c_permutation.json"
    if not f.exists():
        return
    r = json.loads(f.read_text())
    lines += ["## P1c. Within-subject permutation null", "",
              "| encoder | observed BA | null mean (sd) | null max | p | n_perm |",
              "|---|---|---|---|---|---|"]
    for n, x in r["encoders"].items():
        lines.append(f"| {n} | {x['observed_BA']:.3f} | {x['null_mean']:.3f} ({x['null_sd']:.3f}) | "
                     f"{x['null_max']:.3f} | {x['p']:.4f} | {x['n_perm']} |")
    lines.append("")


def main() -> int:
    lines = ["# Phase 1 result tables (generated by experiments/summarize_phase1.py)", "",
             "BA = balanced accuracy, subject-level bootstrap 95% CI. Chance = 0.333.", ""]
    p1a(lines)
    p1b(lines)
    p1c(lines)
    text = "\n".join(lines)
    (ROOT / "docs" / "PHASE1_RESULTS_TABLES.md").write_text(text + "\n")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
